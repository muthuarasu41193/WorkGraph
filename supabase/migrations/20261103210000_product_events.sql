-- First-party product funnel events (Prompt 12). Server-only via service role.
-- Idempotent. Safe to run in the Supabase SQL Editor.
-- No PII in props: no emails, names, resume text, or job descriptions.
-- Account delete: anonymise user_id (see lib/account/data-map.ts).

create table if not exists public.product_events (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users (id) on delete set null,
  event text not null,
  props jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

alter table public.product_events drop constraint if exists product_events_event_check;
alter table public.product_events
  add constraint product_events_event_check
  check (event in (
    'signup',
    'resume_uploaded',
    'match_viewed',
    'tailoring_run',
    'cover_letter',
    'pass_checkout_started',
    'pass_purchased',
    'vault_purchased',
    'digest_sent',
    'digest_unsubscribed',
    'application_added',
    'follow_up_marked'
  ));

create index if not exists product_events_created_at_idx
  on public.product_events (created_at desc);

create index if not exists product_events_event_created_idx
  on public.product_events (event, created_at desc);

create index if not exists product_events_user_id_idx
  on public.product_events (user_id)
  where user_id is not null;

comment on table public.product_events is
  'First-party product funnel events. props must stay small (~1 KB) and must not contain PII. Service role only; account delete anonymises user_id.';
comment on column public.product_events.props is
  'Small JSON object of enums/numbers only. No emails, names, resume text, or job descriptions.';

alter table public.product_events enable row level security;

-- No policies for authenticated or anon. Service role bypasses RLS.
revoke all on table public.product_events from public, anon, authenticated;

do $$
begin
  if exists (select 1 from pg_roles where rolname = 'service_role') then
    grant select, insert, update, delete on table public.product_events to service_role;
  end if;
end $$;

do $$
begin
  if exists (select 1 from pg_roles where rolname = 'service_role')
     and exists (
       select 1 from pg_class c
       join pg_namespace n on n.oid = c.relnamespace
       where n.nspname = 'public' and c.relname = 'product_events_id_seq'
     ) then
    grant usage, select on sequence public.product_events_id_seq to service_role;
  end if;
end $$;
